import {readFile,writeFile,mkdir,copyFile} from "node:fs/promises";
import path from "node:path";
const base="https://shop-magic-maker-82.lovable.app";
const root="shop/replica";
await mkdir(path.join(root,"assets/products"),{recursive:true});
let html=await readFile("shop/reference/original.html","utf8");
const stylesheet=html.match(/href="(\/assets\/styles-[^"]+\.css)"/)?.[1];
if(!stylesheet)throw Error("Original stylesheet not found");
const cssResp=await fetch(base+stylesheet);
if(!cssResp.ok)throw Error("Original CSS unavailable "+cssResp.status);
const extra=await readFile("shop/replica-extra.css","utf8");
const css=await cssResp.text();
await writeFile(path.join(root,"styles.css"),css+"\n"+extra,"utf8");
const pattern=/\/__l5e\/assets-v1\/[a-z0-9-]+\/(p\d+_\d+\.jpg)/g;
const images=[...new Map([...html.matchAll(pattern)].map(m=>[m[0],m[1]])).entries()];
const fetches=images.map(async ([url,file])=>{
 const resp=await fetch(base+url,{headers:{"User-Agent":"Mozilla/5.0"}});
 if(!resp.ok)throw Error("Product image unavailable "+url+" "+resp.status);
 const data=new Uint8Array(await resp.arrayBuffer());
 if(data[0]!==255||data[1]!==216||data.length<2000)throw Error("Image is not JPEG "+file);
 await writeFile(path.join(root,"assets/products",file),data);
 return {file,bytes:data.length};
});
const copied=await Promise.all(fetches);
for(const [url,file] of images)html=html.split(url).join("assets/products/"+file);
html=html.replace(/<meta name="author" content="Lovable">/g,"").replace(/<meta name="twitter:site" content="@Lovable">/g,"");
html=html.replace(/<meta(?: property="og:image"| name="twitter:image")[^>]*>/g,"");
html=html.replace(/<link rel="modulepreload"[^>]*>/g,"");
html=html.replace(/<link rel="stylesheet" href="\/assets\/styles-[^"]+\.css"[^>]*>/,'<link rel="stylesheet" href="styles.css">');
html=html.replace(/<link rel="icon" href="\/favicon.ico"[^>]*>/,"");
html=html.replace(/<style>[\s\S]*?#lovable-badge[\s\S]*?<\/style>/,"");
html=html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,"");
html=html.replace(/<aside id="lovable-badge"[\s\S]*?<\/aside>/,"");
html=html.replace(/<html lang="en">/,'<html lang="ru">');
html=html.replace(/<title>[^<]*<\/title>/,'<title>Lixiang Аксессуары — каталог L6, L7, L8, L9</title>');
html=html.replace(/<\/head>/,'<meta name="theme-color" content="#f7f3ed"><meta name="referrer" content="strict-origin-when-cross-origin"></head>');
html=html.replace(/<\/body>/,'<script src="app.js" defer></script></body>');
if(/lovable-badge|__l5e|\/assets\/styles-|\/assets\/index-/.test(html))throw Error("Lovable dependency remains in HTML");
await writeFile(path.join(root,"index.html"),html,"utf8");
await copyFile("shop/replica-app.js",path.join(root,"app.js"));
console.log("REPLICA_OK", "original CSS",css.length,"html",html.length,"photos",copied.length,"bytes",copied.reduce((a,x)=>a+x.bytes,0));
